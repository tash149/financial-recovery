"""Generate the synthetic document images used by the demo.

Run from backend/:  .venv/bin/python -m seed.generate_images

Writes three PNGs next to this file:
- death_certificate.png            genuine certificate for Rajesh Kumar Sharma
- impostor_death_certificate.png   same layout, edited date of death in a different font
- share_certificate.png            old (1994) physical share certificate

Output is deterministic (fixed random seed), so the committed images can be regenerated byte-for-byte.
Every image carries a visible "SYNTHETIC DEMO DOCUMENT" mark.
"""

import json
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

SEED_DIR = Path(__file__).resolve().parent
FONT_DIRS = [Path("/usr/share/fonts/truetype/liberation"), Path("/usr/share/fonts/truetype/dejavu")]

# Genuine documents use Liberation Serif; the impostor's edited date uses DejaVu Sans.
SERIF = "LiberationSerif-Regular.ttf"
SERIF_BOLD = "LiberationSerif-Bold.ttf"
SERIF_ITALIC = "LiberationSerif-Italic.ttf"
SANS = "DejaVuSans.ttf"
SANS_BOLD = "DejaVuSans-Bold.ttf"

PAPER = (250, 247, 240)
INK = (28, 28, 34)
MUTED = (90, 90, 100)
STAMP_BLUE = (40, 70, 150)


def font(name: str, size: int) -> ImageFont.FreeTypeFont:
    for d in FONT_DIRS:
        path = d / name
        if path.exists():
            return ImageFont.truetype(str(path), size)
    raise FileNotFoundError(f"Font {name} not found in {FONT_DIRS}. Install fonts-liberation and fonts-dejavu-core.")


def centered(draw: ImageDraw.ImageDraw, y: int, text: str, f, width: int, fill=INK) -> None:
    w = draw.textlength(text, font=f)
    draw.text(((width - w) / 2, y), text, font=f, fill=fill)


def demo_mark(img: Image.Image, text: str = "SYNTHETIC DEMO DOCUMENT - NOT VALID") -> Image.Image:
    """Diagonal faint watermark plus a solid band at the top."""
    w, h = img.size
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    f = font(SANS_BOLD, max(28, w // 30))
    tile = Image.new("RGBA", (int(d.textlength(text, font=f)) + 40, f.size + 20), (0, 0, 0, 0))
    ImageDraw.Draw(tile).text((20, 10), text, font=f, fill=(200, 40, 40, 38))
    tile = tile.rotate(28, expand=True)
    for y in range(-tile.height // 2, h, tile.height + 40):
        for x in range(-tile.width // 2, w, tile.width):
            layer.alpha_composite(tile, (x, y))
    out = Image.alpha_composite(img.convert("RGBA"), layer)
    d = ImageDraw.Draw(out)
    d.rectangle([0, 0, w, 34], fill=(200, 40, 40, 255))
    centered(d, 6, "DEMO · SYNTHETIC DATA · NOT A REAL DOCUMENT", font(SANS_BOLD, 20), w, fill=(255, 255, 255))
    return out.convert("RGB")


def round_stamp(draw: ImageDraw.ImageDraw, cx: int, cy: int, r: int, lines: list[str]) -> None:
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], outline=STAMP_BLUE, width=4)
    draw.ellipse([cx - r + 12, cy - r + 12, cx + r - 12, cy + r - 12], outline=STAMP_BLUE, width=2)
    f = font(SANS_BOLD, 17)
    y = cy - len(lines) * 12
    for line in lines:
        w = draw.textlength(line, font=f)
        draw.text((cx - w / 2, y), line, font=f, fill=STAMP_BLUE)
        y += 24


def signature(draw: ImageDraw.ImageDraw, x: int, y: int, rng: random.Random) -> None:
    pts = []
    for i in range(40):
        pts.append((x + i * 6, y + int(14 * ((i % 7) - 3) / 3) + rng.randint(-4, 4)))
    draw.line(pts, fill=(20, 30, 90), width=3, joint="curve")


# ---------------------------------------------------------------- death certificate

def death_certificate(fields: dict, impostor_date_of_death: str | None = None) -> Image.Image:
    """Render the certificate. If impostor_date_of_death is given, the date-of-death value is
    painted over and re-typed in a different font, slightly larger and off the baseline."""
    W, H = 1240, 1754
    img = Image.new("RGB", (W, H), PAPER)
    d = ImageDraw.Draw(img)
    rng = random.Random(7)

    d.rectangle([40, 60, W - 40, H - 40], outline=INK, width=4)
    d.rectangle([52, 72, W - 52, H - 52], outline=INK, width=1)

    centered(d, 110, "REGISTRAR OF BIRTHS & DEATHS, DELHI", font(SERIF_BOLD, 40), W)
    centered(d, 162, "(Demo registry for a synthetic test case)", font(SERIF_ITALIC, 24), W, fill=MUTED)
    centered(d, 230, "DEATH CERTIFICATE", font(SERIF_BOLD, 54), W)
    centered(d, 300, "Issued under Section 12 / 17 of the Registration of Births & Deaths Act, 1969", font(SERIF, 22), W, fill=MUTED)
    d.line([120, 350, W - 120, 350], fill=INK, width=2)

    centered(
        d, 375,
        "This is to certify that the following information has been taken from the original record of death",
        font(SERIF, 22), W,
    )
    centered(d, 405, "which is in the register for the local area of Delhi.", font(SERIF, 22), W)

    rows = [
        ("Registration No.", fields["registration_no"]),
        ("Date of Registration", _ddmmyyyy(fields["date_of_registration"])),
        ("Name of Deceased", fields["name_of_deceased"]),
        ("Sex", fields["sex"]),
        ("Age at Death", fields["age_at_death"]),
        ("Date of Death", _ddmmyyyy(fields["date_of_death"])),
        ("Place of Death", fields["place_of_death"]),
        ("Name of Father", fields["father_name"]),
        ("Name of Spouse", fields["spouse_name"]),
        ("Address at Time of Death", fields["address_at_death"]),
        ("Permanent Address", fields["permanent_address"]),
    ]
    label_f, value_f = font(SERIF_BOLD, 28), font(SERIF, 30)
    y, label_x, value_x = 480, 130, 560
    date_box = None
    for label, value in rows:
        d.text((label_x, y), label, font=label_f, fill=INK)
        d.text((value_x - 30, y), ":", font=label_f, fill=INK)
        d.text((value_x, y), value, font=value_f, fill=INK)
        if label == "Date of Death":
            date_box = (value_x, y, value)
        d.line([value_x, y + 40, W - 130, y + 40], fill=(200, 196, 186), width=1)
        y += 72

    if impostor_date_of_death and date_box:
        x, yy, old = date_box
        old_w = d.textlength(old, font=value_f)
        # Paint-over patch: pure white, slightly larger than the old text, visibly off the paper tone.
        d.rectangle([x - 6, yy - 4, x + old_w + 18, yy + 38], fill=(255, 255, 255))
        d.text((x + 2, yy + 5), _ddmmyyyy(impostor_date_of_death), font=font(SANS, 31), fill=(10, 10, 10))

    y += 30
    centered(d, y, f"Date of Issue: {_ddmmyyyy(fields['date_of_issue'])}", font(SERIF, 26), W)
    round_stamp(d, 300, H - 300, 120, ["REGISTRAR", "BIRTHS & DEATHS", "DELHI · DEMO"])
    signature(d, W - 470, H - 330, rng)
    d.text((W - 470, H - 280), "Signature of Issuing Authority", font=font(SERIF, 22), fill=INK)
    d.text((W - 470, H - 250), "Registrar (Births & Deaths)", font=font(SERIF_ITALIC, 22), fill=MUTED)
    centered(d, H - 110, "Every death must be registered within 21 days of occurrence.", font(SERIF_ITALIC, 20), W, fill=MUTED)

    return demo_mark(img)


def _ddmmyyyy(iso: str) -> str:
    y, m, dd = iso.split("-")
    return f"{dd}-{m}-{y}"


# ---------------------------------------------------------------- share certificate

def share_certificate() -> Image.Image:
    W, H = 1600, 1100
    rng = random.Random(1994)
    paper = (236, 224, 192)
    img = Image.new("RGB", (W, H), paper)
    d = ImageDraw.Draw(img)
    green = (40, 90, 60)

    # Guilloche-style border: nested frames plus a ring of small diamonds.
    d.rectangle([30, 30, W - 30, H - 30], outline=green, width=6)
    d.rectangle([50, 50, W - 50, H - 50], outline=green, width=2)
    for x in range(70, W - 60, 28):
        for yy in (62, H - 72):
            d.polygon([(x, yy), (x + 8, yy + 8), (x, yy + 16), (x - 8, yy + 8)], outline=green)
    for yy in range(90, H - 80, 28):
        for x in (62, W - 62):
            d.polygon([(x, yy), (x + 8, yy + 8), (x, yy + 16), (x - 8, yy + 8)], outline=green)

    d.text((110, 110), "Certificate No. 0041172", font=font(SERIF_BOLD, 26), fill=INK)
    d.text((W - 420, 110), "Folio No. R001893", font=font(SERIF_BOLD, 26), fill=INK)
    centered(d, 160, "BHARAT TEXTILE MILLS LIMITED", font(SERIF_BOLD, 64), W, fill=green)
    centered(d, 240, "(Incorporated under the Indian Companies Act, 1913)", font(SERIF_ITALIC, 26), W)
    centered(d, 278, "Registered Office: Naroda Road, Ahmedabad 380025", font(SERIF, 24), W)
    centered(d, 340, "SHARE CERTIFICATE", font(SERIF_BOLD, 48), W)
    centered(d, 400, "Authorised Capital Rs. 50,00,00,000 divided into 5,00,00,000 Equity Shares of Rs. 10/- each", font(SERIF, 22), W)

    body = [
        "THIS IS TO CERTIFY that the person named below is the Registered Holder of the",
        "fully paid-up Equity Shares of Rs. 10/- each, numbered as below, in the above-named Company,",
        "subject to the Memorandum and Articles of Association of the Company.",
    ]
    yy = 470
    for line in body:
        centered(d, yy, line, font(SERIF, 26), W)
        yy += 38

    rows = [
        ("Name of Holder", "RAJESH KUMAR SHARMA"),
        ("Number of Shares", "200 (TWO HUNDRED) only"),
        ("Distinctive Nos.", "1045201  to  1045400"),
    ]
    yy = 620
    for label, value in rows:
        d.text((300, yy), label, font=font(SERIF_BOLD, 30), fill=INK)
        d.text((640, yy), ":  " + value, font=font(SERIF, 32), fill=INK)
        yy += 56

    d.text((300, 820), "Given under the Common Seal of the Company this 12th day of August, 1994.", font=font(SERIF_ITALIC, 26), fill=INK)
    round_stamp(d, 260, 940, 90, ["SEAL", "BTM LTD", "1994"])
    for i, title in enumerate(["Director", "Director", "Secretary"]):
        x = 620 + i * 300
        signature(d, x, 930, rng)
        d.text((x + 40, 975), title, font=font(SERIF, 24), fill=INK)

    # Ageing: fold line, foxing spots, a tea stain, slight blur.
    d.line([W // 2, 40, W // 2 + 6, H - 40], fill=(214, 200, 165), width=3)
    for _ in range(260):
        x, y0, r = rng.randint(40, W - 40), rng.randint(40, H - 40), rng.randint(1, 4)
        tone = rng.randint(185, 215)
        d.ellipse([x - r, y0 - r, x + r, y0 + r], fill=(tone, tone - 18, tone - 55))
    stain = Image.new("L", (W, H), 0)
    ImageDraw.Draw(stain).ellipse([1180, 700, 1420, 900], fill=60)
    stain = stain.filter(ImageFilter.GaussianBlur(30))
    img = Image.composite(Image.new("RGB", (W, H), (200, 170, 120)), img, stain)
    img = img.filter(ImageFilter.GaussianBlur(0.6))
    return demo_mark(img)


def main() -> None:
    registry = json.loads((SEED_DIR / "digilocker_mock.json").read_text())["death_registry"]["records"]
    genuine = next(r for r in registry if r["doc_id"] == "dl-death-rks")["fields"]
    claim = json.loads((SEED_DIR / "impostor_claim.json").read_text())["claim"]

    death_certificate(genuine).save(SEED_DIR / "death_certificate.png", optimize=True)
    death_certificate(genuine, impostor_date_of_death=claim["deceased_as_stated"]["date_of_death"]).save(
        SEED_DIR / "impostor_death_certificate.png", optimize=True
    )
    share_certificate().save(SEED_DIR / "share_certificate.png", optimize=True)
    print("Wrote death_certificate.png, impostor_death_certificate.png, share_certificate.png")


if __name__ == "__main__":
    main()
